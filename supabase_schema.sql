-- 1. Create the Bookings Table
create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  token_no text not null,
  temple_id text not null,
  vazhipadu_name text not null,
  devotee_name text not null,
  nakshathram text not null,
  date text not null,
  time text not null,
  amount numeric not null default 0,
  status text not null default 'Ready for Collection',
  collected boolean not null default false,
  phone text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. Fast Lookup Indexes
create index if not exists idx_bookings_temple_id on public.bookings (temple_id);
create index if not exists idx_bookings_token_no on public.bookings (token_no);
create index if not exists idx_bookings_collected on public.bookings (collected);
create index if not exists idx_bookings_created_at on public.bookings (created_at desc);

-- 3. Enable Row Level Security (RLS)
alter table public.bookings enable row level security;

-- 4. Public Policies for Temple QR Platform
-- Drop existing policies if re-running
drop policy if exists "Enable read access for all users" on public.bookings;
drop policy if exists "Enable insert access for all users" on public.bookings;
drop policy if exists "Enable update access for all users" on public.bookings;

create policy "Enable read access for all users" 
  on public.bookings for select 
  using (true);

create policy "Enable insert access for all users" 
  on public.bookings for insert 
  with check (true);

create policy "Enable update access for all users" 
  on public.bookings for update 
  using (true);

-- 5. Enable Realtime Publications (Instant WebSocket alerts when devotees book)
alter publication supabase_realtime add table public.bookings;

